async def translate(key: str, default: Optional[str] = None, **kwargs: Any) -> str:
    lang = await get_language()
    if lang not in TRANSLATIONS:
        lang = "zh"
    catalog = TRANSLATIONS[lang]
    text = catalog.get(key) or default or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except KeyError:
            return text
    return text
